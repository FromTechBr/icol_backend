-- V1__baseline.sql
-- PostgreSQL

CREATE TABLE usuarios_icol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_usuario VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    tipo_usuario VARCHAR(30) NOT NULL
);

CREATE TABLE cursos_icol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_curso VARCHAR(255) NOT NULL,
    descricao VARCHAR(255) NOT NULL,
    duracao VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    categoria VARCHAR(30) NOT NULL,
    matricula_automatica BOOLEAN NOT NULL DEFAULT FALSE,
    limite_faltas_percentual NUMERIC(5, 2),

    CONSTRAINT chk_cursos_limite_faltas
        CHECK (
            limite_faltas_percentual IS NULL
            OR limite_faltas_percentual BETWEEN 0 AND 100
        )
);

CREATE TABLE alunos_icol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    nome_completo VARCHAR(255) NOT NULL,
    idade INTEGER NOT NULL,
    cpf VARCHAR(255) NOT NULL UNIQUE,
    telefone VARCHAR(255) NOT NULL,
    decla_socie VARCHAR(255) NOT NULL,
    endereco VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_alunos_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios_icol (id)
);

CREATE TABLE docentes_icol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE,
    nome_completo VARCHAR(255) NOT NULL,
    especializacao VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_docentes_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios_icol (id)
);

CREATE TABLE turmas_icol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_turma VARCHAR(30) NOT NULL,
    curso_id BIGINT NOT NULL,
    docente_id BIGINT NOT NULL,
    num_max_alunos INTEGER NOT NULL,
    cronograma_horarios VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_turmas_curso
        FOREIGN KEY (curso_id) REFERENCES cursos_icol (id),

    CONSTRAINT fk_turmas_docente
        FOREIGN KEY (docente_id) REFERENCES docentes_icol (id)
);

CREATE TABLE avisos_mural (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    turma_id BIGINT,
    titulo VARCHAR(255) NOT NULL,
    conteudo VARCHAR(255) NOT NULL,
    data_postagem TIMESTAMP NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_avisos_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuarios_icol (id),

    CONSTRAINT fk_avisos_turma
        FOREIGN KEY (turma_id) REFERENCES turmas_icol (id)
);

CREATE TABLE matricula_icol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_matricula DATE NOT NULL,
    status_matricula VARCHAR(30) NOT NULL,
    aluno_id BIGINT NOT NULL,
    turma_id BIGINT NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    situacao_final VARCHAR(30),

    CONSTRAINT fk_matriculas_aluno
        FOREIGN KEY (aluno_id) REFERENCES alunos_icol (id),

    CONSTRAINT fk_matriculas_turma
        FOREIGN KEY (turma_id) REFERENCES turmas_icol (id)
);

CREATE TABLE frequencia_icol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_aula DATE NOT NULL,
    justificativa VARCHAR(255),
    status_presenca VARCHAR(30) NOT NULL,
    matricula_id BIGINT NOT NULL,

    CONSTRAINT fk_frequencias_matricula
        FOREIGN KEY (matricula_id) REFERENCES matricula_icol (id)
);

CREATE INDEX idx_alunos_usuario_id
    ON alunos_icol (usuario_id);

CREATE INDEX idx_turmas_curso_id
    ON turmas_icol (curso_id);

CREATE INDEX idx_turmas_docente_id
    ON turmas_icol (docente_id);

CREATE INDEX idx_avisos_usuario_id
    ON avisos_mural (usuario_id);

CREATE INDEX idx_avisos_turma_id
    ON avisos_mural (turma_id);

CREATE INDEX idx_matriculas_aluno_id
    ON matricula_icol (aluno_id);

CREATE INDEX idx_matriculas_turma_id
    ON matricula_icol (turma_id);

CREATE INDEX idx_frequencias_matricula_id
    ON frequencia_icol (matricula_id);